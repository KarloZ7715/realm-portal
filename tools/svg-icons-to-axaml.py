#!/usr/bin/env python3
"""Convert assets/icons/ui/*.svg (24x24 line icons) into src/RealmPortal.App/Theme/Icons.axaml.

Usage (from the repository root): python3 tools/svg-icons-to-axaml.py
Only <path>, <circle> and <rect> elements are supported (that is all the icon set uses).
"""
import glob
import os
import xml.etree.ElementTree as ET

HEADER = '''<ResourceDictionary xmlns="https://github.com/avaloniaui"
                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">
  <!--
    UI icons: the 23 line icons of assets/icons/ui converted to geometries on a 24x24 grid.
    Generated by tools/svg-icons-to-axaml.py (run it again if the SVGs change). Draw them with the Icon
    control, which strokes with the inherited Foreground, so one icon works on leather and on parchment.
    "IconPlay" and "IconDiamond" are filled shapes (Icon.IsFilled="True"); all others are strokes.
  -->
'''
FOOTER = '''  <!-- Check mark for checkboxes (the circled "ok" icon is too busy at 12 px). Hand-written, not generated. -->
  <StreamGeometry x:Key="IconCheckMark">M5,12.5 L10,17.5 L19,7</StreamGeometry>
</ResourceDictionary>
'''


def circle(cx: float, cy: float, r: float) -> str:
    return f"M{cx - r},{cy} a{r},{r} 0 1 0 {2 * r},0 a{r},{r} 0 1 0 {-2 * r},0 z"


def main() -> None:
    out = [HEADER]
    for path in sorted(glob.glob("assets/icons/ui/*.svg")):
        name = os.path.basename(path)[:-4]
        parts = []
        for el in ET.parse(path).getroot():
            tag = el.tag.split("}")[1]
            if tag == "path":
                parts.append(el.get("d"))
            elif tag == "circle":
                parts.append(circle(float(el.get("cx")), float(el.get("cy")), float(el.get("r"))))
            elif tag == "rect":
                x, y, w, h = (float(el.get(k)) for k in ("x", "y", "width", "height"))
                parts.append(f"M{x},{y} h{w} v{h} h{-w} z")
            else:
                raise SystemExit(f"unsupported element <{tag}> in {path}")
        key = "Icon" + "".join(p.capitalize() for p in name.split("-"))
        out.append(f'  <StreamGeometry x:Key="{key}">{" ".join(parts)}</StreamGeometry>\n')
    out.append(FOOTER)
    with open("src/RealmPortal.App/Theme/Icons.axaml", "w", encoding="utf-8", newline="\n") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main()
